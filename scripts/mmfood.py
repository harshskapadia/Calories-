"""Real-world photos with calorie labels (MM-Food-100K) -> CLIP features -> calorie/macro estimator.

    python scripts/mmfood.py sample --n 6000          # pick photos (20% of DISH NAMES held out as unseen)
    python scripts/mmfood.py download                 # fetch + shrink images (parallel), keep 256 px JPEGs
    python scripts/mmfood.py features                 # CLIP image embeddings with the same int8 ONNX model the web app uses

Dataset: Humanbased-AI/MM-Food-100K (OpenRAIL). ~100k crowd-sourced, mostly phone photos with dish name, portion and
nutrition. Its nutrition labels were generated by GPT-4o / Qwen and then reviewed by crowd annotators, so they are
estimates: models trained on them learn to agree with those reviewed estimates, not with weighed measurements.
"""

from __future__ import annotations

import argparse
import io
import sys
import time
import urllib.request
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
RAW = ROOT / "data" / "raw" / "mmfood"
IMG = RAW / "images"
UA = "NutriSnap/1.0 (portfolio project; https://github.com/harshskapadia/Calories-)"


def sample(n: int, seed: int = 0, holdout: float = 0.2) -> None:
    df = pd.read_parquet(RAW / "meta.parquet")
    df = df[(df.food_prob >= 0.8) & df.calories_kcal.between(10, 3000)].copy()
    df["dish"] = df.dish_name.str.lower().str.strip()
    names = df.dish.drop_duplicates().sample(frac=1, random_state=seed)
    unseen = set(names.iloc[: int(len(names) * holdout)])
    df["split"] = np.where(df.dish.isin(unseen), "test_unseen", "train")
    picked = df.sample(n=min(n, len(df)), random_state=seed)
    picked = picked.reset_index().rename(columns={"index": "row"})
    picked.to_parquet(RAW / "sample.parquet")
    print(picked.split.value_counts().to_dict(), "| dishes:", picked.dish.nunique())


def download(workers: int = 16) -> None:
    from PIL import Image

    IMG.mkdir(parents=True, exist_ok=True)
    df = pd.read_parquet(RAW / "sample.parquet")

    def get(row) -> bool:
        out = IMG / f"{row.row}.jpg"
        if out.exists():
            return True
        for attempt in range(3):
            try:
                req = urllib.request.Request(row.image_url, headers={"User-Agent": UA})
                with urllib.request.urlopen(req, timeout=60) as r:
                    im = Image.open(io.BytesIO(r.read())).convert("RGB")
                s = 256 / min(im.size)
                if s < 1:
                    im = im.resize((round(im.width * s), round(im.height * s)), Image.BICUBIC)
                im.save(out, "JPEG", quality=88)
                return True
            except Exception:
                time.sleep(2 ** attempt)
        return False

    t = time.time()
    with ThreadPoolExecutor(workers) as ex:
        ok = sum(ex.map(get, df.itertuples()))
    print(f"{ok}/{len(df)} images in {time.time() - t:.0f}s")


VIEWS = ["bicubic", "bicubic_flip", "bilinear", "box_crop"]


def views(im, mean, std, rng):
    """4 versions of one photo: the regressor trains on all of them so it ignores resize/crop/mirror details
    (estimates moved by ~10% between interpolation methods before this). Test/browser use mean(view 0, view 1)."""
    from PIL import Image, ImageOps
    from torchvision import transforms as T

    norm = T.Compose([T.ToTensor(), T.Normalize(mean, std)])

    def resize_crop(img, mode, short=224, crop=224, jitter=False):
        sc = short / min(img.size)
        r = img.resize((max(crop, round(img.width * sc)), max(crop, round(img.height * sc))), mode)
        if jitter:
            l, t = rng.integers(0, r.width - crop + 1), rng.integers(0, r.height - crop + 1)
        else:
            l, t = (r.width - crop) // 2, (r.height - crop) // 2
        return r.crop((l, t, l + crop, t + crop))

    base = resize_crop(im, Image.BICUBIC)
    return [norm(base), norm(ImageOps.mirror(base)), norm(resize_crop(im, Image.BILINEAR)),
            norm(resize_crop(im, Image.BOX, short=256, jitter=True))]


def features(batch: int = 32) -> None:
    import json

    import onnxruntime as ort
    import torch
    from PIL import Image

    meta = json.loads((ROOT / "docs" / "model" / "clip_vocab.json").read_text(encoding="utf-8"))
    sess = ort.InferenceSession(str(ROOT / "docs" / "model" / "clip_visual.int8.onnx"))
    df = pd.read_parquet(RAW / "sample.parquet")
    df = df[[(IMG / f"{r}.jpg").exists() for r in df.row]].reset_index(drop=True)
    rng = np.random.default_rng(0)
    out = np.zeros((len(df), len(VIEWS), meta["dim"]), np.float16)
    for i in range(0, len(df), batch):
        xs = []
        for r in df.row[i:i + batch]:
            xs += views(Image.open(IMG / f"{r}.jpg").convert("RGB"), meta["mean"], meta["std"], rng)
        e = sess.run(None, {"image": torch.stack(xs).numpy()})[0]
        out[i:i + batch] = e.reshape(-1, len(VIEWS), meta["dim"])
        if i % 3200 == 0:
            print(f"  {i}/{len(df)}", flush=True)
    np.save(RAW / "features.npy", out)
    df.to_parquet(RAW / "features_meta.parquet")
    print(f"features for {len(df)} images x {len(VIEWS)} views")


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("cmd", choices=["sample", "download", "features"])
    ap.add_argument("--n", type=int, default=6000)
    a = ap.parse_args()
    {"sample": lambda: sample(a.n), "download": download, "features": features}[a.cmd]()
